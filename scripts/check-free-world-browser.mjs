import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? '../../my-portfolio/node_modules/playwright/index.mjs');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const base = process.env.LAB_URL ?? 'http://127.0.0.1:5174';
await mkdir('screenshots/free-world', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [], requests = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('request', (request) => requests.push(request.url()));
  await page.goto(`${base}/?world=free&inspect=1`, { waitUntil: 'networkidle' });
  const read = () => page.evaluate(() => window.__freeWorld());
  await page.waitForFunction(() => window.__freeWorld?.().cells === 125);
  await page.screenshot({ path: 'screenshots/free-world/01-ready.png' });
  assert.equal(requests.some((url) => /\/src\/main.js|star_noise|milkyway|Lenis/i.test(url)), false);
  await page.getByRole('button', { name: 'Enter world' }).click();
  await page.waitForFunction(() => window.__freeWorld().locked);
  console.log('Real click acquires pointer lock.');
  await page.mouse.wheel(0, 240);
  await page.waitForTimeout(650);
  const first = await read();
  assert.ok(Math.abs(first.position[2] + 8.4) < 0.02);
  assert.ok(Math.abs(first.position[0]) < 0.001);
  console.log('Scroll advances along initial -Z heading:', first.position);
  await page.mouse.move(1000, 350);
  await page.waitForTimeout(100);
  const looked = await read();
  assert.ok(Math.abs(looked.yaw) > 0.01);
  assert.ok(looked.position.every((n, i) => Math.abs(n - first.position[i]) < 0.001));
  await page.mouse.wheel(0, 240);
  await page.waitForTimeout(650);
  const moved = await read();
  const displacement = moved.position.map((n, i) => n - looked.position[i]);
  assert.ok(displacement.every((n, i) => Math.abs(n - looked.direction[i] * 8.4) < 0.02));
  await page.screenshot({ path: 'screenshots/free-world/02-looking-and-travelling.png' });
  console.log('Mouse look leaves position fixed; subsequent scroll follows new heading.');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !window.__freeWorld().locked);
  await page.getByRole('button', { name: 'Return to origin' }).click();
  await page.getByRole('combobox', { name: 'Travel speed' }).selectOption('10');
  await page.getByRole('button', { name: 'Enter world' }).click();
  await page.waitForFunction(() => window.__freeWorld().locked);
  await page.mouse.wheel(0, 240);
  await page.waitForTimeout(650);
  const fast = await read();
  assert.ok(Math.abs(fast.position[2] + 84) < 0.03);
  assert.equal(fast.cells, 125);
  assert.ok(fast.geometries > 0 && fast.geometries <= 125);
  await page.mouse.wheel(0, -240);
  await page.waitForTimeout(650);
  const back = await read();
  assert.ok(Math.hypot(...back.position) < 0.03);
  assert.equal(back.cells, 125);
  assert.ok(back.geometries > 0 && back.geometries <= 125);
  console.log('10x crosses cells; reverse scroll returns; uploaded geometry stays within the 125-cell bound.');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !window.__freeWorld().locked);
  const stopped = await read();
  await page.mouse.wheel(0, 300);
  await page.waitForTimeout(100);
  assert.deepEqual((await read()).position, stopped.position);
  console.log('Escape releases cursor; uncaptured scroll cannot move the camera.');
  assert.deepEqual(errors, []);
  console.log('Free-world browser QA passed.');
} finally { await browser.close(); }
